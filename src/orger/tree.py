"""
*Tree*: like a :class:`~orger.Mirror`, but the output is a directory of org files.

Some data is better in many files than in one: a file for each event or each
project, with a file or two that gather them.  A Tree is regenerated from
scratch every time, like a Mirror, and so its files are read-only.  But because
the directory may be synchronised or indexed, it also takes care that

- a file whose text has not changed is not written, so its modification time
  and everything that watches it are left alone;
- a file appears all at once (a temporary file next to it is renamed), so
  nothing meets half of one;
- nothing is ever deleted or moved: a file that is no longer made stays where it
  was.  What is generated has stationary paths, and anything else that lives
  beside it -- text extracted from attachments, say -- is not in danger.
"""

from __future__ import annotations

import os
import stat
import tempfile
from collections.abc import Iterable, Sequence
from pathlib import Path

from .atomic_append import assert_not_edited
from .inorganic import OrgNode
from .org_view import OrgView


class Tree(OrgView):
    DEFAULT_HEADER = '''
# This file is AUTOGENERATED by {tool}
# It's deliberately read-only, because it will be overwritten next time Orger is run.
# If you want to edit it anyway, you can use chmod +w in your terminal, or M-x toggle-read-only in Emacs.
'''.lstrip()

    #: A file: its path relative to the output directory, lines to start it with (such as
    #: ``#+title: ...``; may be empty), and the top level entries of it.
    Files = Iterable[tuple[str, str, Sequence[OrgNode]]]

    #: The directory being written, once it is known, so that a view can see what is already there.
    output: Path | None = None

    @classmethod
    def main(cls, setup_parser=None) -> None:
        p = cls.parser()
        og = p.add_mutually_exclusive_group()
        og.add_argument('--to', type=Path, default=Path(cls.name()), help='Directory to output')
        og.add_argument(
            '--stdout', action='store_true', help='pass to print output to stdout, useful for testing/debugging'
        )
        if setup_parser is not None:
            setup_parser(p)

        args = p.parse_args()
        inst = cls(cmdline_args=args)
        inst.main_common()
        inst._run(to=args.to, stdout=args.stdout)

    def get_files(self) -> Tree.Files:
        raise NotImplementedError

    def make_files(self) -> dict[str, str]:
        """The text of every file, by path."""
        header_lines = self.file_header.splitlines(keepends=True)
        made: dict[str, str] = {}
        for path, start, items in self.get_files():
            check_path(path)
            if path in made:
                raise RuntimeError(f'{path} is made twice')
            split = header_lines + start.splitlines(keepends=True)
            root = OrgNode(
                heading=split[0].rstrip(),
                body=''.join(split[1:]),
                children=list(items),
                escaped=True,
            )
            made[path] = root.render(level=0) + '\n'
        return made

    def _run(self, to: Path, *, stdout: bool) -> None:
        self.output = to
        made = self.make_files()
        if stdout:
            for path, text in sorted(made.items()):
                print(f'# ==== {path}')
                print(text)
            return

        written = 0
        for path, text in sorted(made.items()):
            written += write_if_changed(to / path, text)
        self.logger.info('%d files made, %d written, %d unchanged', len(made), written, len(made) - written)


def check_path(path: str) -> None:
    """
    >>> check_path('a/b.org')
    >>> check_path('../x.org')
    Traceback (most recent call last):
    ...
    ValueError: not a path inside the output directory: ../x.org
    """
    parts = Path(path).parts
    if not parts or Path(path).is_absolute() or '..' in parts:
        raise ValueError(f'not a path inside the output directory: {path}')


def write_if_changed(target: Path, text: str) -> int:
    """
    Make ``target`` hold ``text``, read-only, and say whether it had to be written.
    """
    assert_not_edited(target)
    if target.exists() and target.read_text(encoding='utf-8') == text:
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix=f'.{target.name}.', suffix='.orger-tmp', dir=target.parent)
    try:
        with os.fdopen(handle, 'w', encoding='utf-8') as stream:
            stream.write(text)
        umask = os.umask(0)
        os.umask(umask)
        Path(temporary).chmod((0o666 & ~umask) & ~(stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH))
        Path(temporary).replace(target)  # the directory is writable, so this works over a read-only file
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    return 1


def test_write_if_changed(tmp_path: Path) -> None:
    f = tmp_path / 'd' / 'x.org'
    assert write_if_changed(f, 'one\n') == 1
    assert f.read_text() == 'one\n'
    assert not os.access(f, os.W_OK)
    before = f.stat().st_mtime_ns
    assert write_if_changed(f, 'one\n') == 0
    assert f.stat().st_mtime_ns == before
    assert write_if_changed(f, 'two\n') == 1  # replaced although read-only
    assert f.read_text() == 'two\n'
    assert [p.name for p in f.parent.iterdir()] == ['x.org']


def test_tree(tmp_path: Path) -> None:
    class T(Tree):
        def get_files(self) -> Tree.Files:
            yield 'a/one.org', '#+title: One\n', [OrgNode(heading='first', body='text')]
            yield 'two.org', '', []

    t = T()
    made = t.make_files()
    assert sorted(made) == ['a/one.org', 'two.org']
    assert '#+title: One' in made['a/one.org']
    assert '* first' in made['a/one.org']
    t._run(tmp_path, stdout=False)
    assert (tmp_path / 'a' / 'one.org').read_text() == made['a/one.org']
    (tmp_path / 'other.txt').write_text('beside')
    t._run(tmp_path, stdout=False)
    assert (tmp_path / 'other.txt').read_text() == 'beside'  # never deleted
